#!/usr/bin/env node
// Verifies the PWA build artefacts together (installability is manifest + icons + service worker +
// HTTPS + a reachable origin, not just an icon):
//
//   node scripts/assert-pwa-build.mjs [distDir]      (run after `npm run build`)
//
// It cannot prove HTTPS or that a host serves the files without a login redirect: a Vercel Preview behind
// Deployment Protection answers every asset (manifest, sw.js, icons) with a 302, which makes Chrome show a
// generic icon and "this app cannot be installed". That is a hosting setting, not a code defect.
import { existsSync, readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

/** width/height of a PNG from its IHDR chunk (no image library needed). */
export function pngSize(buffer) {
  const signature = '89504e470d0a1a0a'
  if (buffer.length < 24 || buffer.subarray(0, 8).toString('hex') !== signature) return null
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) }
}

const need = (list, ok, message) => {
  if (!ok) list.push(message)
}

export function pwaProblems(dist) {
  const problems = []
  const file = (name) => join(dist, name)
  need(problems, existsSync(file('manifest.webmanifest')), 'dist/manifest.webmanifest is missing (the manifest must be a build output)')
  need(problems, existsSync(file('sw.js')), 'dist/sw.js is missing')
  need(problems, existsSync(file('registerSW.js')), 'dist/registerSW.js is missing')
  need(problems, existsSync(file('index.html')), 'dist/index.html is missing')
  // a hand-maintained copy in public/ would be copied into dist and could shadow the generated manifest
  need(problems, !existsSync(join(dist, '..', 'public', 'manifest.webmanifest')), 'public/manifest.webmanifest must not exist: the manifest is generated by vite.config.ts')
  need(problems, !existsSync(join(dist, '..', 'public', 'manifest.json')), 'public/manifest.json must not exist')
  if (problems.length) return problems

  const manifest = JSON.parse(readFileSync(file('manifest.webmanifest'), 'utf8'))
  need(problems, manifest.id === '/', 'manifest.id must be "/"')
  need(problems, Boolean(manifest.name) && Boolean(manifest.short_name), 'manifest needs name and short_name')
  need(problems, manifest.start_url === '/' && manifest.scope === '/', 'manifest start_url and scope must be "/"')
  need(problems, manifest.display === 'standalone', 'manifest.display must be standalone')
  need(problems, /^#[0-9a-f]{6}$/i.test(manifest.theme_color ?? '') && /^#[0-9a-f]{6}$/i.test(manifest.background_color ?? ''), 'manifest needs theme_color and background_color')
  const icons = manifest.icons ?? []
  const find = (size, purpose) => icons.find((i) => i.sizes === size && (i.purpose ?? 'any').split(' ').includes(purpose))
  for (const [size, purpose] of [['192x192', 'any'], ['512x512', 'any'], ['512x512', 'maskable']]) {
    const icon = find(size, purpose)
    need(problems, Boolean(icon), `manifest needs a ${size} ${purpose} icon`)
    if (!icon) continue
    const path = file(icon.src.replace(/^\//, ''))
    need(problems, existsSync(path), `${icon.src} is referenced but not built`)
    if (!existsSync(path)) continue
    const dims = pngSize(readFileSync(path))
    const expected = Number(size.split('x')[0])
    need(problems, dims?.width === expected && dims?.height === expected, `${icon.src} must be a real ${size} PNG`)
  }
  const maskable = find('512x512', 'maskable')
  if (maskable && existsSync(file(maskable.src.replace(/^\//, '')))) {
    // full-bleed: a maskable icon with transparent pixels shows white corners under Android's mask. PNG colour type 2 = RGB (no alpha).
    const colorType = readFileSync(file(maskable.src.replace(/^\//, ''))).readUInt8(25)
    need(problems, colorType === 2, `${maskable.src} must be full-bleed (opaque RGB, no alpha channel)`)
  }

  const apple = file('apple-touch-icon.png')
  need(problems, existsSync(apple) && pngSize(readFileSync(apple))?.width === 180 && pngSize(readFileSync(apple))?.height === 180, 'apple-touch-icon.png must be 180x180')
  need(problems, existsSync(file('favicon.svg')) && existsSync(file('favicon-32x32.png')), 'favicon.svg and favicon-32x32.png must be built')

  const html = readFileSync(file('index.html'), 'utf8')
  need(problems, /<link rel="manifest" href="\/manifest\.webmanifest"/.test(html), 'index.html must link the manifest')
  need(problems, /<link rel="apple-touch-icon"[^>]*apple-touch-icon\.png/.test(html), 'index.html must link the apple-touch-icon')
  need(problems, html.includes(`content="${manifest.theme_color}"`) && /name="theme-color"/.test(html), 'the theme-color meta must equal manifest.theme_color')

  const sw = readFileSync(file('sw.js'), 'utf8')
  for (const asset of ['index.html', 'manifest.webmanifest', 'pwa-192x192.png', 'pwa-512x512.png', 'pwa-maskable-512x512.png', 'apple-touch-icon.png']) {
    need(problems, sw.includes(`"${asset}"`), `sw.js does not precache ${asset}`)
  }
  need(problems, sw.includes('cleanupOutdatedCaches') || sw.includes('cleanupOutdatedCaches()'), 'sw.js must clean up outdated caches (cache/version behaviour)')
  need(problems, /serviceWorker\.register\('\/sw\.js'/.test(readFileSync(file('registerSW.js'), 'utf8')), 'registerSW.js must register /sw.js')
  return problems
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const dist = resolve(process.argv[2] ?? 'dist')
  const problems = pwaProblems(dist)
  if (problems.length) {
    console.error(`PWA build check FAILED:\n- ${problems.join('\n- ')}`)
    process.exitCode = 1
  } else {
    console.log(`PWA build check OK (${dist}): manifest, icons (192/512 any, 512 maskable full-bleed, apple 180), service worker precache, registration.`)
    console.log('Note: HTTPS and an unprotected host are required for installation; a login-protected Preview cannot be installed.')
  }
}
